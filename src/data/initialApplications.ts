export const createStandardTimeline = (status: ApplicationStatus, createdDate = 'Nov 01, 2026'): ApplicationTimelineEvent[] => {
  const isSubmittedOrPast = ['Submitted', 'Under Review', 'Awarded', 'Rejected'].includes(status);
  const isUnderReviewOrPast = ['Under Review', 'Awarded', 'Rejected'].includes(status);
  const isDecisionPast = ['Awarded', 'Rejected'].includes(status);

  return [
    {
      id: 'step-1',
      title: 'Application Created',
      stage: 'created',
      date: createdDate,
      completed: true,
      notes: 'Record initiated in BEACON Application Command Center',
    },
    {
      id: 'step-2',
      title: 'Documents Prepared',
      stage: 'documents',
      date: status === 'Saved' ? 'In Progress' : 'Nov 03, 2026',
      completed: status !== 'Saved',
      notes: status === 'Saved' ? 'Gathering required deliverables' : 'Core transcripts and statements ready',
    },
    {
      id: 'step-3',
      title: 'Application Submitted',
      stage: 'submitted',
      date: isSubmittedOrPast ? 'Nov 05, 2026' : 'Target: Nov 20, 2026',
      completed: isSubmittedOrPast,
      notes: isSubmittedOrPast ? 'Packet transmitted via sponsor portal' : 'Awaiting final document sign-off',
    },
    {
      id: 'step-4',
      title: 'Under Review',
      stage: 'under_review',
      date: isUnderReviewOrPast ? 'Nov 06, 2026' : 'Pending submission',
      completed: isUnderReviewOrPast,
      notes: isUnderReviewOrPast ? 'Academic review committee evaluation underway' : 'To be queued upon transmission',
    },
    {
      id: 'step-5',
      title: 'Decision Received',
      stage: 'decision',
      date: isDecisionPast ? (status === 'Awarded' ? 'Oct 25, 2026' : 'Sep 20, 2026') : 'Est. Dec 15, 2026',
      completed: isDecisionPast,
      notes: status === 'Awarded' ? 'Grant awarded and accepted' : (status === 'Rejected' ? 'Not selected for this cycle' : 'Pending committee conclusion'),
    },
  ];
};

export const calculateApplicationProgress = (
  documents: ApplicationDocument[],
  timeline: ApplicationTimelineEvent[],
  status: ApplicationStatus
): number => {
  // Awarded represents 100% complete and successfully granted
  if (status === 'Awarded') {
    return 100;
  }

  // 1. Documents checklist score (50% weight)
  const docWeights: Record<DocumentChecklistStatus, number> = {
    ready: 1.0,
    pending: 0.35,
    missing: 0.0,
  };

  const totalDocScore = documents.reduce((sum, doc) => sum + docWeights[doc.status], 0);
  const docRatio = documents.length > 0 ? totalDocScore / documents.length : 0.5;

  // 2. Timeline milestone score (50% weight)
  const completedTimelineEvents = timeline.filter((e) => e.completed).length;
  const timelineRatio = timeline.length > 0 ? completedTimelineEvents / timeline.length : 0.2;

  // For rejected applications, readiness reflects the document and pre-submission prep achieved,
  // and is never artificially inflated or displayed as completed preparation (Phase 2 Data Integrity rule).
  if (status === 'Rejected') {
    const preDecisionMilestones = timeline.filter((e) => e.completed && e.stage !== 'decision').length;
    const preRatio = timeline.length > 1 ? preDecisionMilestones / (timeline.length - 1) : 0.5;
    return Math.min(75, Math.round(docRatio * 45 + preRatio * 35));
  }

  // Stage baseline floor
  const statusFloors: Record<ApplicationStatus, number> = {
    'Saved': 15,
    'Applying': 40,
    'Submitted': 75,
    'Under Review': 88,
    'Awarded': 100,
    'Rejected': 0,
  };

  const calculated = Math.round(docRatio * 50 + timelineRatio * 50);
  const finalScore = Math.max(statusFloors[status], Math.min(95, calculated));

  return finalScore;
};


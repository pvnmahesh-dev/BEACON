/**
 * Computes deterministic matches dynamically for any student profile.
 * Every scholarship record receives an evaluated match score, status,
 * satisfied/unsatisfied requirements list, missing information list,
 * and clear explanation.
 */
export function getComputedScholarships(student: UserProfile): Scholarship[] {
  return rawScholarshipsData.map((sch) => {
    const match = calculateEligibilityMatch(student, sch);
    return {
      ...sch,
      matchScore: match.matchPercentage,
      eligibilityStatus: match.status,
      statusLabel: match.statusLabel,
      statusColor: match.statusColor,
      requirementsSatisfied: match.requirementsSatisfied,
      requirementsNotSatisfied: match.requirementsNotSatisfied,
      missingInformation: match.missingInformation,
      explanation: match.explanation,
      disqualifyingReason: match.disqualifyingReason,
      matchFactors: match.factors,
    };
  });
}

// Default export initialized with default demo student
export const initialScholarshipDatabase: Scholarship[] = getComputedScholarships(currentUser);
